/**
 * Menghitung jarak Haversine (km) antara dua koordinat
 */
function haversineDistance(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371; // km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

/**
 * Reverse Geocoding Ringan: Menemukan kota/kabupaten terdekat di Indonesia berdasarkan koordinat GPS
 */
export function findNearestIndonesianCity(lat: number, lng: number): { city: IndonesianCity; distanceKm: number } {
  let closest = INDONESIA_CITIES[0];
  let minDistance = haversineDistance(lat, lng, closest.lat, closest.lng);

  for (let i = 1; i < INDONESIA_CITIES.length; i++) {
    const item = INDONESIA_CITIES[i];
    const dist = haversineDistance(lat, lng, item.lat, item.lng);
    if (dist < minDistance) {
      minDistance = dist;
      closest = item;
    }
  }

  return {
    city: closest,
    distanceKm: Math.round(minDistance * 10) / 10,
  };
}
